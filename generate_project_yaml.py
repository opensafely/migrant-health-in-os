
# Script to generate the project yaml

from pathlib import Path
import yaml

from analysis.qof_dictionary import *


actions = {}

for disease_name, config in DISEASES.items():

    output_name = config.get("output_name", disease_name)

    output_dir = (
        f"output/tables/annual_counts/{output_name}"
    )

    actions[f"{disease_name}_prev"] = {
        "run": (
            "ehrql:v1 generate-measures "
            "analysis/measures.py "
            f"--output {output_dir}/:csv "
            f"-- --disease {disease_name}"
        ),
        "outputs": {
            "moderately_sensitive": {
                "csv": f"{output_dir}/*.csv"
            }
        },
    }

project = {
    "version": "5.0",
    "actions": actions,
}

header = (
    "# This is an AUTO-GENERATED FILE - Do not edit it manually\n"
    "# It is generated by analysis/generate_project_yaml.py\n"
    "# To make changes, update analysis/disease_dictionary.py\n"
    "# and rerun: python -m generate_project_yaml\n\n"
)

Path("project.yaml").write_text(
    header + yaml.safe_dump(
        project,
        sort_keys=False,
    )
)
